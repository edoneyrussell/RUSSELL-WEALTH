"""Optional PostgreSQL checks using session-local temporary tables only.

Set RW_TEST_POSTGRES_URL to exercise the actual PostgreSQL adapter. No real
account rows are read or changed; all account tables are shadowed in pg_temp.
"""
import os
import unittest
from unittest.mock import patch

import test_access


@unittest.skipUnless(os.environ.get('RW_TEST_POSTGRES_URL'), 'No PostgreSQL test connection configured')
class PostgresAccessTests(unittest.TestCase):
    setUpClass = classmethod(test_access.AccessTests.setUpClass.__func__)
    tearDownClass = classmethod(test_access.AccessTests.tearDownClass.__func__)
    client = test_access.AccessTests.client

    def setUp(self):
        test_access.AccessTests.setUp(self)
        import psycopg
        from psycopg.rows import dict_row
        from postgres_adapter import PostgresAdapter
        adapter = object.__new__(PostgresAdapter)
        adapter.connection = psycopg.connect(os.environ['RW_TEST_POSTGRES_URL'], row_factory=dict_row, connect_timeout=10)
        self.addCleanup(adapter.connection.close)
        definitions = {
            'users': "id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL, role TEXT NOT NULL, account_status TEXT DEFAULT 'ACTIVE', access_version INTEGER DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP",
            'admin_customer_links': 'admin_user_id INTEGER, customer_user_id INTEGER, PRIMARY KEY(admin_user_id, customer_user_id)',
            'investment_accounts': 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER, account_name TEXT, cash_balance_cents INTEGER DEFAULT 0',
            'holdings': 'account_id INTEGER',
            'transactions': 'account_id INTEGER',
            'security_events': 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER, event_type TEXT, source_ip TEXT, severity TEXT, details TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP',
            'rw_demo_bank_accounts': 'user_id INTEGER',
            'rw_demo_bank_transfers': 'user_id INTEGER',
            'customer_preferences': 'user_id INTEGER',
            'password_reset_codes': 'email TEXT',
            'pending_registrations': 'email TEXT',
        }
        for table, fields in definitions.items():
            adapter.execute(f'CREATE TEMP TABLE {table} ({fields})')
        for uid, email, role in [(401, 'user101@example.com', 'SOC_ADMIN'), (402, 'other@example.com', 'SOC_ADMIN'), (103, 'member@example.com', 'CUSTOMER')]:
            adapter.execute('INSERT INTO users (id,name,email,password_hash,role) VALUES (?,?,?,?,?)',
                            (uid, 'Temporary Test Account', email, self.password_hash, role))
        adapter.commit()
        # Closing an endpoint's connection rolls back its reads while preserving
        # the session-local tables for the next request in this test.
        self.real = adapter
        self.connection_patch = patch('access_api.source_connection', side_effect=lambda source, primary:
                                      self.remote() if source == 'live' else self.local())
        self.connection_patch.start()
        self.addCleanup(self.connection_patch.stop)
        self.sources_patch = patch('access_api.directory_sources', return_value=('local', ['local', 'live']))
        self.sources_patch.start()
        self.addCleanup(self.sources_patch.stop)

    def local(self):
        import database
        return database.get_db_connection()

    def remote(self):
        adapter = self.real
        class Connection:
            execute = adapter.execute
            commit = adapter.commit
            rollback = adapter.rollback
            close = adapter.rollback
        return Connection()

    def test_postgres_automatic_authorization_roles_suspension_and_deletion(self):
        response = self.admin.patch('/api/security/users/103?source=live', json={'current_password': 'test-password-12345', 'role': 'BOTH'})
        self.assertEqual(response.status_code, 200, response.json)
        directory = self.admin.get('/api/security/users')
        live = [row for row in directory.json['users'] if row['source'] == 'live' and row['id'] == 103]
        self.assertEqual(live[0]['access_role'], 'BOTH')
        self.assertTrue(live[0]['manageable'])
        for status in ('SUSPENDED', 'ACTIVE'):
            response = self.admin.patch('/api/security/users/103?source=live', json={'current_password': 'test-password-12345', 'account_status': status})
            self.assertEqual(response.status_code, 200, response.json)
        response = self.admin.delete('/api/security/users/103?source=live', json={'current_password': 'test-password-12345', 'confirm_email': 'member@example.com'})
        self.assertEqual(response.status_code, 200, response.json)
        self.assertIsNone(self.real.execute('SELECT id FROM users WHERE id=103').fetchone())
        self.assertEqual(self.real.execute("SELECT COUNT(*) AS n FROM security_events WHERE event_type='ACCOUNT_DELETED' AND user_id=401").fetchone()['n'], 1)
