BEGIN;

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL,
    account_status TEXT NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    profile_photo_data TEXT,
    profile_photo_mime TEXT
);

CREATE TABLE security_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id),
    event_type TEXT NOT NULL,
    source_ip TEXT,
    severity TEXT NOT NULL,
    details TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE investment_accounts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    account_name TEXT NOT NULL DEFAULT 'Investment Portfolio',
    cash_balance_cents INTEGER NOT NULL DEFAULT 0 CHECK (cash_balance_cents >= 0),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE assets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    asset_type TEXT NOT NULL,
    currency TEXT NOT NULL DEFAULT 'CAD',
    price_cents INTEGER NOT NULL CHECK (price_cents > 0)
);

CREATE TABLE holdings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INTEGER NOT NULL REFERENCES investment_accounts(id),
    asset_id INTEGER NOT NULL REFERENCES assets(id),
    quantity TEXT NOT NULL DEFAULT '0',
    UNIQUE (account_id, asset_id)
);

CREATE TABLE transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INTEGER NOT NULL REFERENCES investment_accounts(id),
    asset_id INTEGER REFERENCES assets(id),
    transaction_type TEXT NOT NULL
        CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'BUY', 'SELL')),
    quantity TEXT,
    amount_cents INTEGER NOT NULL CHECK (amount_cents >= 0),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE admin_customer_links (
    admin_user_id INTEGER NOT NULL REFERENCES users(id),
    customer_user_id INTEGER NOT NULL REFERENCES users(id),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (admin_user_id, customer_user_id)
);

CREATE TABLE security_incidents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    severity TEXT NOT NULL DEFAULT 'WARNING',
    status TEXT NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'INVESTIGATING', 'RESOLVED')),
    source_ip TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TEXT
);

CREATE INDEX idx_incident_status ON security_incidents(status);

CREATE TABLE security_alerts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER REFERENCES security_events(id),
    alert_type TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT,
    severity TEXT NOT NULL DEFAULT 'WARNING',
    source_ip TEXT,
    status TEXT NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'DISMISSED')),
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dismissed_at TEXT
);

CREATE INDEX idx_security_alert_status ON security_alerts(status);
CREATE INDEX idx_security_alert_created ON security_alerts(created_at);

CREATE TABLE incident_notes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id INTEGER NOT NULL REFERENCES security_incidents(id),
    analyst_id INTEGER NOT NULL,
    note TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE market_quotes (
    symbol TEXT PRIMARY KEY,
    price TEXT NOT NULL,
    currency TEXT NOT NULL,
    provider TEXT NOT NULL,
    as_of TEXT,
    refreshed_at TEXT NOT NULL
);

CREATE TABLE market_history (
    symbol TEXT PRIMARY KEY,
    history_json TEXT NOT NULL,
    provider TEXT NOT NULL,
    refreshed_at TEXT NOT NULL
);

CREATE TABLE market_metadata (
    cache_key TEXT PRIMARY KEY,
    cache_value TEXT NOT NULL
);

CREATE TABLE market_fx_rates (
    pair TEXT PRIMARY KEY,
    rate TEXT NOT NULL,
    rate_date TEXT NOT NULL,
    refreshed_at TEXT NOT NULL
);

CREATE INDEX idx_market_quotes_refreshed ON market_quotes(refreshed_at);

CREATE TABLE rw_demo_bank_accounts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    bank_code TEXT NOT NULL,
    balance_cents INTEGER NOT NULL DEFAULT 100000000 CHECK (balance_cents >= 0),
    UNIQUE (user_id, bank_code)
);

CREATE TABLE rw_demo_bank_transfers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id TEXT NOT NULL UNIQUE,
    request_id TEXT,
    user_id INTEGER NOT NULL,
    bank_code TEXT NOT NULL,
    direction TEXT NOT NULL CHECK (direction IN ('DEPOSIT', 'WITHDRAW')),
    amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX rw_demo_transfer_request_unique
    ON rw_demo_bank_transfers(user_id, request_id)
    WHERE request_id IS NOT NULL;

COMMIT;
